import argparse
import hashlib
import json
import os
import sys
from dataclasses import asdict
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(
        description="Export workloads generated by the original CC_v3.2 project."
    )

    parser.add_argument(
        "--cc-root",
        default=os.environ.get("CC_ROOT", r"..\CC_v3.2")
    )
    parser.add_argument("--source", default="SYNTHETIC",
                        choices=["SYNTHETIC", "ALIBABA", "GOOGLE_BORG"])
    parser.add_argument("--size", type=int, default=5)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--deadline-tier", default="MEDIUM",
                        choices=["TIGHT", "MEDIUM", "RELAXED"])
    parser.add_argument("--dataset-split", default="TEST",
                        choices=["CALIBRATION", "VALIDATION", "TEST"])
    parser.add_argument("--output", default="data/ccv2_workload_seed42.json")

    args = parser.parse_args()

    cc_root = Path(args.cc_root).resolve()
    if not cc_root.is_dir():
        raise FileNotFoundError(f"CC_v3.2 directory not found: {cc_root}")

    sys.path.insert(0, str(cc_root))

    from backend.app.datasets import load_workload

    jobs = load_workload(
        args.source,
        args.size,
        args.seed,
        args.deadline_tier
    )

    job_records = sorted(
        (asdict(job) for job in jobs),
        key=lambda item: (item["arrival_time"], item["job_id"])
    )

    required_fields = {
        "job_id", "job_type", "arrival_time", "deadline",
        "estimated_runtime", "cpu_required", "memory_required", "priority"
    }

    for index, job in enumerate(job_records):
        missing = required_fields - set(job)
        if missing:
            raise ValueError(f"Job {index} is missing fields: {sorted(missing)}")

        if job["arrival_time"] < 0:
            raise ValueError(f"Negative arrival time: {job['job_id']}")

        if job["estimated_runtime"] <= 0:
            raise ValueError(f"Invalid runtime: {job['job_id']}")

        if job["deadline"] < job["arrival_time"]:
            raise ValueError(f"Invalid deadline: {job['job_id']}")

    job_ids = [job["job_id"] for job in job_records]
    if len(job_ids) != len(set(job_ids)):
        raise ValueError("Duplicate job IDs detected.")

    canonical_jobs = json.dumps(
        job_records,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True
    )

    input_hash = hashlib.sha256(
        canonical_jobs.encode("utf-8")
    ).hexdigest()

    group_id = (
        f"SYNTHETIC_SEED:{args.seed}"
        if args.source == "SYNTHETIC"
        else f"{args.source}:deterministic-trace-prefix"
    )

    payload = {
        "schema_version": "ccv2.workload.v1",
        "source": args.source,
        "seed": args.seed,
        "deadline_tier": args.deadline_tier,
        "dataset_split": args.dataset_split,
        "dataset_group_id": group_id,
        "runtime_estimate_source": (
            "synthetic model"
            if args.source == "SYNTHETIC"
            else "historical trace runtime; not a runtime predictor"
        ),
        "jobs": job_records,
        "input_hash": input_hash
    }

    output_path = Path(args.output).resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)

    output_path.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False),
        encoding="utf-8"
    )

    print("\nWORKLOAD EXPORT SUCCESSFUL")
    print(f"Source:       {args.source}")
    print(f"Job count:    {len(job_records)}")
    print(f"Seed:         {args.seed}")
    print(f"Deadline:     {args.deadline_tier}")
    print(f"Input hash:   {input_hash}")
    print(f"Output file:  {output_path}")

    print("\nEXPORTED JOBS")
    for job in job_records:
        print(
            f"{job['job_id']} | "
            f"arrival={job['arrival_time']:.6f} | "
            f"deadline={job['deadline']:.6f} | "
            f"runtime={job['estimated_runtime']:.6f} | "
            f"CPU={job['cpu_required']} | "
            f"RAM={job['memory_required']} MiB"
        )


if __name__ == "__main__":
    main()
